// Writes config.js with the Supabase project URL and publishable (anon) key for the page to read.
// Values come from the environment (the Pages workflow) or, for local use, from a .env file beside the repo root.
// usage: node scripts/make-config.mjs [output path, default config.js]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(process.argv[2] || join(root, 'config.js'));

const file = {};
const envPath = join(root, '.env');
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (!m || line.trim().startsWith('#')) continue;
    file[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}
const pick = name => String(process.env[name] || file[name] || '').trim();

const url = pick('SUPABASE_URL').replace(/\/+$/, '');
const key = pick('SUPABASE_ANON_KEY');
const adminEmails = [...new Set(pick('ADMIN_EMAILS').split(/[\s,;]+/).map(s => s.trim().toLowerCase()).filter(s => s.includes('@')))];

if (url && !/^https?:\/\/[\w.\-]+(:\d+)?$/.test(url)) { console.error('SUPABASE_URL should look like https://your-project.supabase.co'); process.exit(1); }
// a page is public: only the anon or publishable key may go into it
function role(k) {
  if (/^sb_secret_/i.test(k)) return 'secret';
  if (/^sb_publishable_[\w\-]{10,}$/.test(k)) return 'ok';
  const p = k.split('.');
  if (p.length !== 3) return 'bad';
  try { const j = JSON.parse(Buffer.from(p[1], 'base64url').toString()); return j.role === 'anon' ? 'ok' : j.role === 'service_role' ? 'secret' : 'bad'; }
  catch { return 'bad'; }
}
if (key) {
  const r = role(key);
  if (r === 'secret') { console.error('SUPABASE_ANON_KEY is a secret (service_role) key. Use the anon or publishable key.'); process.exit(1); }
  if (r === 'bad') { console.error('SUPABASE_ANON_KEY does not look like a Supabase anon or publishable key.'); process.exit(1); }
}

const cfg = {};
if (url) cfg.supabaseUrl = url;
if (key) cfg.supabaseAnonKey = key;
if (adminEmails.length) cfg.adminEmails = adminEmails;
writeFileSync(out, '// generated by scripts/make-config.mjs; do not commit\nwindow.INVOICE_SCRAPER_CONFIG = ' + JSON.stringify(cfg) + ';\n');
console.log('Wrote ' + out + ' (Supabase URL ' + (url ? 'set' : 'not set') + ', key ' + (key ? 'set' : 'not set') + ', admin emails ' + adminEmails.length + ')');
